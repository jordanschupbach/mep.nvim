--- Curated colorscheme palettes, keyed by name. Each is a compact,
--- ~13-field "base16-ish" palette (`dark`, `bg`, `fg`, seven accent
--- hues, plus a few structural colors) rather than a hand-tuned,
--- hundred-group theme per entry — `mep.theme.engine` is the one
--- shared renderer that turns any such palette into a full Neovim
--- highlight set, the same "small palette drives everything" idea
--- `mep-wm`'s own `{fg, bg, accent}` themes use, just with a few more
--- hues than that project needs (a real window manager has no syntax
--- categories to color).
---
--- Required fields: `dark` (boolean — sets `'background'`), `bg`, `fg`,
--- `red`, `green`, `yellow`, `blue`, `purple`, `cyan`, `orange`,
--- `border`. Optional, each falling back sensibly if omitted (see
--- `mep.theme.engine.normalize`): `bg_alt` (→ `bg`), `bg_float` (→
--- `bg_alt`), `fg_alt` (→ `fg`), `selection` (→ `border`), `accent` (→
--- `blue`).
---
--- Real, publicly documented palette values for each of these — not
--- guesses — cross-checked against `~/projects/mep-wm`'s own built-in
--- theme list (`dark`/`nord`/`dracula`/`gruvbox-dark`/`tokyo-night`/
--- `catppuccin-mocha`/`one-dark`/`everforest-dark` and their light
--- counterparts share this project's own `fg`/`bg`/`accent` values)
